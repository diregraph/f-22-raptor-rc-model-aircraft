// Writes the two ArduPilot Lua scripts from the design numbers, so the autopilot mixes the motors the aircraft
// actually has. Run after any change to spec.js or nozzle.js:  node tools/ardupilot-gen.mjs
//   ardupilot/scripts/f35b_frame.lua   motor layout for Q_FRAME_CLASS = 15 (Scripting Matrix)
//   ardupilot/scripts/f35b_nozzle.lua  tilt + yaw demand -> the two nozzle cord-drum servos
import { writeFileSync } from 'node:fs';
import { createSim } from '../site/js/sim.js';
import { D, massProps, hoverTrim, nozzleExit } from '../site/js/spec.js';
import { NOZZLE, jointCentres } from '../site/js/nozzle.js';

const sim = createSim(), [F, M, L, R] = sim.thrusters, mp = massProps(D.battery.xDefault), trim = hoverTrim(mp, 90);
const eff = nozzleExit(90).eff;
// vertical thrust each motor gives at full output in the hover, and where it acts (m from the balance point; x forward, z right)
const mot = [
  { id: 'F', name: 'lift fan', Tv: F.max, x: F.r[0], z: F.r[2], share: trim.F / (F.max / 9.81 * 1000) },
  { id: 'M', name: 'main fan (swivel nozzle)', Tv: M.max * eff, x: M.r[0], z: M.r[2], share: trim.M / (M.max / 9.81 * 1000) },
  { id: 'L', name: 'roll fan left', Tv: L.max, x: L.r[0], z: L.r[2], share: trim.L / (L.max / 9.81 * 1000) },
  { id: 'R', name: 'roll fan right', Tv: R.max, x: R.r[0], z: R.r[2], share: trim.R / (R.max / 9.81 * 1000) },
];
// Minimum-effort factors that give a pure moment with no change in total lift (and no roll from pitch or pitch from roll):
// f = A^T (A A^T)^-1 b, with rows of A = lift, roll moment, pitch moment per unit output of each motor.
function pureAxis(row) {
  const A = [mot.map(m => m.Tv), mot.map(m => -m.Tv * m.z), mot.map(m => m.Tv * m.x)];
  const AAt = A.map(a => A.map(b => a.reduce((s, v, i) => s + v * b[i], 0)));
  const inv3 = m => { const [a, b, c] = m[0], [d, e, f] = m[1], [g, h, i] = m[2], det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g);
    return [[e * i - f * h, c * h - b * i, b * f - c * e], [f * g - d * i, a * i - c * g, c * d - a * f], [d * h - e * g, b * g - a * h, a * e - b * d]].map(r => r.map(v => v / det)); };
  const y = inv3(AAt).map(r => r.reduce((s, v, i) => s + v * (i === row ? 1 : 0), 0));
  return mot.map((_, j) => A.reduce((s, a, i) => s + a[j] * y[i], 0));
}
const roll = pureAxis(1), pitch = pureAxis(2), big = Math.max(...mot.map(m => m.share));
const f3 = v => (Math.abs(v) < 1e-9 ? 0 : v).toFixed(4);
const lines = mot.map((m, i) => `MotorsMatrix:add_motor_raw(${i}, ${f3(roll[i])}, ${f3(pitch[i])}, 0, ${i + 1})   -- motor ${i + 1}: ${m.name}`).join('\n');
const thr = mot.map((m, i) => `MotorsMatrix:set_throttle_factor(${i}, ${f3(m.share / big)})`).join('\n');

writeFileSync(new URL('../ardupilot/scripts/f35b_frame.lua', import.meta.url), `-- F-35B model motor layout for ArduPilot QuadPlane, Q_FRAME_CLASS = 15 (Scripting Matrix).
-- GENERATED by tools/ardupilot-gen.mjs from site/js/spec.js. Do not edit by hand.
--
-- Roll and pitch factors give a pure moment with no change in total lift, so the unequal fans mix correctly.
-- Yaw factors are zero: the fans' torque is too weak to steer with. Hover yaw comes from swinging the nozzle
-- jet sideways (f35b_nozzle.lua reads the yaw demand). Throttle factors set each fan's share of the hover lift
-- from the static trim (lift fan and roll pair at ${(trim.fLift * 100).toFixed(0)}%, nozzle at ${(trim.fMain * 100).toFixed(0)}% of full thrust).
-- Motor 2 is the one that tilts: Q_TILT_MASK = 2.

${lines}
assert(MotorsMatrix:init(4), "f35b: MotorsMatrix init failed")
${thr}
motors:set_frame_string("F-35B lift fan + roll pair + swivel nozzle")
`);

const jc = jointCentres();
writeFileSync(new URL('../ardupilot/scripts/f35b_nozzle.lua', import.meta.url), `-- F-35B model swivel nozzle: turns ArduPilot's tilt and yaw demands into the two cord-drum servo positions.
-- GENERATED by tools/ardupilot-gen.mjs; the maths is a line-for-line port of site/js/nozzle.js.
--
-- Inputs : SERVOn_FUNCTION 41 (motor tilt, 0 = jet straight down, 1000 = straight aft) and motors:get_yaw() (-1..1).
-- Outputs: SERVOn_FUNCTION 94 (Script1) = servo 1, bearing-1 collar; 95 (Script2) = servo 2, drive ring.
-- Yaw: ArduPilot's positive yaw is nose right. A jet pushed to the right at the tail swings the nose left, so
-- nose right needs the jet swung left: swing = -yaw x the swing limit at this deflection.

local ALPHA, MAXDEF, MAXYAW = ${NOZZLE.alpha}, ${NOZZLE.maxDeflection}, ${NOZZLE.maxYaw}
local BAND1, RING, COLLAR, DRUM = ${NOZZLE.cord.band1}, ${NOZZLE.cord.ring}, ${NOZZLE.cord.collar}, ${NOZZLE.cord.drum}
local HALF_TRAVEL = ${NOZZLE.servoTravel / 2}                 -- degrees each side of centre for 1000..2000 us
local CENTRE_BAND, CENTRE_RING = ${jc.band.toFixed(4)}, ${jc.ring.toFixed(4)}   -- pulley mid-travel (nozzle.js jointCentres)
local K = COLLAR / RING
local RAD = math.pi / 180
local K_TILT, K_S1, K_S2 = 41, 94, 95

local function rot(ax, t)
  local x, y, z = ax[1], ax[2], ax[3]
  local c, s = math.cos(t), math.sin(t)
  local C = 1 - c
  return { { c + x * x * C, x * y * C - z * s, x * z * C + y * s },
           { y * x * C + z * s, c + y * y * C, y * z * C - x * s },
           { z * x * C - y * s, z * y * C + x * s, c + z * z * C } }
end
local function mm(a, b)
  local r = {}
  for i = 1, 3 do r[i] = {} for j = 1, 3 do r[i][j] = a[i][1] * b[1][j] + a[i][2] * b[2][j] + a[i][3] * b[3][j] end end
  return r
end
local N1 = { 1, 0, 0 }
local N2 = { math.cos(ALPHA * RAD), math.sin(ALPHA * RAD), 0 }
local N3 = { math.cos(ALPHA * RAD), -math.sin(ALPHA * RAD), 0 }
local function exit_dir(a, b, c)
  local m = mm(mm(rot(N1, a * RAD), rot(N2, b * RAD)), rot(N3, c * RAD))
  return { m[1][1], m[2][1], m[3][1] }
end
local function clamp(v, lo, hi) if v < lo then return lo elseif v > hi then return hi end return v end
local function yaw_limit(d) return MAXYAW - math.max(0, d - 90) * 1.2 end

-- wanted deflection (0 = straight aft, 90 = straight down) and yaw swing (deg) -> joint angles a, b
local function solve(deflection, yaw)
  local d = clamp(deflection, 0, MAXDEF)
  local sa = math.sin(ALPHA * RAD)
  local b = 2 * math.asin(math.min(1, math.sin(d * RAD / 4) / sa)) / RAD
  local bz = math.max(b, 0.5)
  local e = exit_dir(0, bz, -bz)
  local az = math.atan(e[3], -e[2]) / RAD
  local yl = yaw_limit(d)
  return az - clamp(yaw, -yl, yl), b
end

local function pwm(deg) return math.floor(1500 + clamp(deg / HALF_TRAVEL, -1, 1) * 500 + 0.5) end

function update()
  local tilt = SRV_Channels:get_output_scaled(K_TILT) / 1000          -- 0 = VTOL (down), 1 = forward (aft)
  local deflection = 90 * (1 - clamp(tilt, 0, 1))
  local yaw = 0
  if quadplane:in_vtol_mode() or quadplane:in_assisted_flight() then yaw = motors:get_yaw() end
  local a, b = solve(deflection, -yaw * yaw_limit(deflection))
  local s1 = (a - CENTRE_BAND) * BAND1 / DRUM
  local s2 = (a + K * b - CENTRE_RING) * RING / DRUM
  SRV_Channels:set_output_pwm(K_S1, pwm(s1))
  SRV_Channels:set_output_pwm(K_S2, pwm(s2))
  return update, 10                                                   -- 100 Hz
end

gcs:send_text(6, "f35b_nozzle running")
return update()
`);
console.log('roll', roll.map(f3).join(' '), '| pitch', pitch.map(f3).join(' '), '| throttle', mot.map(m => f3(m.share / big)).join(' '));
