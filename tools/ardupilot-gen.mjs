// Writes ardupilot/scripts/f35b_frame.lua, the motor layout for Q_FRAME_CLASS = 15 (Scripting Matrix), from the
// design numbers, so the autopilot mixes the fans the aircraft actually has. Run after any change to spec.js:
//   node tools/ardupilot-gen.mjs
// The nozzle script is firmware/nozzle/nozzle_3bsm.lua (kept by the nozzle work, checked by nozzle-firmware-test.mjs).
import { writeFileSync } from 'node:fs';
import { createSim } from '../site/js/sim.js';
import { D, massProps, hoverTrim, nozzleExit } from '../site/js/spec.js';

const sim = createSim(), [F, M, L, R] = sim.thrusters, mp = massProps(D.battery.xDefault), trim = hoverTrim(mp, 90);
const eff = nozzleExit(90).eff;
// vertical thrust each motor gives at full output in the hover, and where it acts (m from the balance point; x forward, z right)
const mot = [
  { id: 'F', name: 'lift fan', Tv: F.max, x: F.r[0], z: F.r[2], share: trim.F / (F.max / 9.81 * 1000) },
  { id: 'M', name: 'main fan (swivel nozzle)', Tv: M.max * eff, x: M.r[0], z: M.r[2], share: trim.M / (M.max / 9.81 * 1000) },
  { id: 'L', name: 'roll fan left', Tv: L.max, x: L.r[0], z: L.r[2], share: trim.L / (L.max / 9.81 * 1000) },
  { id: 'R', name: 'roll fan right', Tv: R.max, x: R.r[0], z: R.r[2], share: trim.R / (R.max / 9.81 * 1000) },
];
// Minimum-effort factors that give a pure moment with no change in total lift (and no roll from pitch or pitch from roll):
// f = A^T (A A^T)^-1 b, with rows of A = lift, roll moment, pitch moment per unit output of each motor.
function pureAxis(row) {
  const A = [mot.map(m => m.Tv), mot.map(m => -m.Tv * m.z), mot.map(m => m.Tv * m.x)];
  const AAt = A.map(a => A.map(b => a.reduce((s, v, i) => s + v * b[i], 0)));
  const inv3 = m => { const [a, b, c] = m[0], [d, e, f] = m[1], [g, h, i] = m[2], det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g);
    return [[e * i - f * h, c * h - b * i, b * f - c * e], [f * g - d * i, a * i - c * g, c * d - a * f], [d * h - e * g, b * g - a * h, a * e - b * d]].map(r => r.map(v => v / det)); };
  const y = inv3(AAt).map(r => r.reduce((s, v, i) => s + v * (i === row ? 1 : 0), 0));
  return mot.map((_, j) => A.reduce((s, a, i) => s + a[j] * y[i], 0));
}
const roll = pureAxis(1), pitch = pureAxis(2), big = Math.max(...mot.map(m => m.share));
const f3 = v => (Math.abs(v) < 1e-9 ? 0 : v).toFixed(4);
const lines = mot.map((m, i) => `MotorsMatrix:add_motor_raw(${i}, ${f3(roll[i])}, ${f3(pitch[i])}, 0, ${i + 1})   -- motor ${i + 1}: ${m.name}`).join('\n');
const thr = mot.map((m, i) => `assert(MotorsMatrix:set_throttle_factor(${i}, ${f3(m.share / big)}), "f35b: throttle factor ${i}")`).join('\n');

writeFileSync(new URL('../ardupilot/scripts/f35b_frame.lua', import.meta.url), `-- F-35B model motor layout for ArduPilot QuadPlane, Q_FRAME_CLASS = 15 (Scripting Matrix).
-- GENERATED by tools/ardupilot-gen.mjs from site/js/spec.js. Do not edit by hand.
--
-- Roll and pitch factors give a pure moment with no change in total lift, so the unequal fans mix correctly.
-- Yaw factors are zero: the fans' torque is too weak to steer with. Hover yaw comes from swinging the nozzle
-- jet sideways (firmware/nozzle/nozzle_3bsm.lua reads the yaw demand). Throttle factors set each fan's share of the hover lift
-- from the static trim (lift fan and roll pair at ${(trim.fLift * 100).toFixed(0)}%, nozzle at ${(trim.fMain * 100).toFixed(0)}% of full thrust).
-- Motor 2 is the one that tilts: Q_TILT_MASK = 2.

${lines}
${thr}                                    -- throttle factors must be set before init()
assert(MotorsMatrix:init(4), "f35b: MotorsMatrix init failed")
motors:set_frame_string("F-35B lift fan + roll pair + swivel nozzle")
`);

console.log('roll', roll.map(f3).join(' '), '| pitch', pitch.map(f3).join(' '), '| throttle', mot.map(m => f3(m.share / big)).join(' '));
